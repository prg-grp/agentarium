#!/usr/bin/env bash
# Generates guest_observer_ebpf/src/vmlinux.rs: Rust bindings for the kernel structs the
# observer's eBPF programs read (task_struct, file, dentry, cred, sock, ...).
#
# The bindings fit exactly the guest kernel that scripts/build-guest.sh pins, because field
# offsets differ between kernel builds. The Makefile runs it when the file is missing or the
# kernel changed; the file isn't committed. It needs target/guest/Image and Docker.
#
# The kernel's BTF (its type information) is part of the uncompressed Image. The script cuts
# it out by its header, then dumps it as C with bpftool and turns that into Rust with
# bindgen, both in a Debian container, since neither runs on macOS.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
IMAGE="$ROOT/target/guest/Image"
BTF="$ROOT/target/guest/vmlinux.btf"
OUT="$ROOT/guest_observer_ebpf/src/vmlinux.rs"

# The structs the programs read; bindgen adds every type they refer to.
TYPES=(
    task_struct linux_binprm mm_struct fs_struct signal_struct cred
    file path dentry qstr inode super_block vfsmount mount
    sock sock_common
)

if [ ! -f "$IMAGE" ]; then
    echo "$IMAGE is missing. Run \`make guest\` first." >&2
    exit 1
fi

# A BTF blob starts with a 24-byte header: magic 0xeb9f, version 1, flags, header length,
# then the offset and length of the type section and of the string section, which follows
# it. The Image may hold more than one blob; the kernel's own is the largest.
python3 -I - "$IMAGE" "$BTF" <<'EOF'
import struct, sys

image, out = sys.argv[1], sys.argv[2]
data = open(image, "rb").read()
best = None
at = data.find(b"\x9f\xeb\x01\x00")
while at >= 0:
    hdr_len, type_off, type_len, str_off, str_len = struct.unpack_from("<5I", data, at + 4)
    if hdr_len == 24 and type_off == 0 and str_off == type_len:
        size = hdr_len + str_off + str_len
        if best is None or size > best[1]:
            best = (at, size)
    at = data.find(b"\x9f\xeb\x01\x00", at + 1)
if best is None:
    sys.exit(f"{image} holds no BTF")
open(out, "wb").write(data[best[0]:best[0] + best[1]])
print(f"cut {best[1]} bytes of BTF out of {image}")
EOF

ALLOW=()
for type in "${TYPES[@]}"; do
    ALLOW+=(--allowlist-type "^${type}\$")
done

docker run --rm --platform linux/arm64 \
    -v "$ROOT:/work" -w /work \
    rust:1-bookworm bash -euc '
        apt-get update -qq
        apt-get install -y -qq bpftool libclang-dev >/dev/null
        rustup component add rustfmt >/dev/null
        cargo install --quiet --locked bindgen-cli
        bpftool btf dump file target/guest/vmlinux.btf format c > /tmp/vmlinux.h
        {
            echo "// Generated by scripts/gen-vmlinux.sh for the pinned guest kernel. Do not edit."
            bindgen /tmp/vmlinux.h "$@" \
                --use-core --ctypes-prefix core::ffi \
                --no-layout-tests --no-doc-comments \
                --default-enum-style consts --no-prepend-enum-name \
                -- -Wno-unknown-attributes
        } > guest_observer_ebpf/src/vmlinux.rs
    ' bash "${ALLOW[@]}"

echo "Bindings written to $OUT"
